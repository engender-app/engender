/* Sign-off renders for the transport both players wear (phase 10 redesign
   ticket 46).

   Only what this ticket changed: the five call sites where somebody plays a
   recording or a video note, each at rest and mid-play, in the default
   palette's two themes and nothing else (the eight-palette cross product
   stays palette-contrast.test.ts's business). The screens around them are
   cropped out - a whole screen shot would be mostly other tickets' work.

   The media is real, generated by media-fixtures.mjs and imported through
   the app's own file picker: the demo journal's own recordings are random
   bytes, which no browser decodes, so a waveform shot against them would be
   a picture of the empty state.

   Run against a demo build, once per side:

     VITE_DEMO=1 npm run build && node tests/media-transport-gallery.mjs \
       --tag after --out /abs/dir

   and, from a detached worktree of main with its own demo build, the same
   script with `--tag before` - `vite preview` serves the working directory
   rather than any root it is handed, so the two sides are two processes in
   two directories. */
import { preview } from 'vite';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchChromium } from './browser-harness.mjs';
import { mediaFixtures } from './media-fixtures.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const at = args.indexOf(`--${name}`);
  return at >= 0 ? args[at + 1] : fallback;
};
const tag = flag('tag', 'after');
const outDir = resolve(flag('out', resolve(here, '../.claude/media-transport-shots')));
const THEMES = ['light', 'dark'];

const media = await mediaFixtures(resolve(here, '../.claude/media-fixtures'));
await mkdir(outDir, { recursive: true });

const browser = await launchChromium({
  args: ['--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required']
});
const app = await preview({ preview: { port: 0 } });
const base = `http://localhost:${app.httpServer.address().port}`;
const fakeMicrophoneSource = (await readFile(`${here}/fake-microphone.mjs`, 'utf8')).replace(
  /^export /gm,
  ''
);

const shots = [];
const errors = [];

let page = await browser.newPage({ viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
const watch = (p) => p.on('pageerror', (err) => errors.push(String(err)));
watch(page);
await page.addInitScript(`
  ${fakeMicrophoneSource}
  window.__fakeMicrophone = installFakeMicrophone('steady');
`);

const settle = async (path) => {
  await page.goto(`${base}${path}`, { waitUntil: 'networkidle' });
  await page.waitForSelector('[data-app-root][data-boot="ready"]', { timeout: 30000 });
  if (await page.locator('[data-leave-setup]').count()) {
    await page.locator('[data-leave-setup]').click();
    await page.waitForSelector('[data-home-hello]');
    await page.goto(`${base}${path}`, { waitUntil: 'networkidle' });
    await page.waitForSelector('[data-app-root][data-boot="ready"]');
  }
};

const dress = async (theme) => {
  await settle('/settings');
  await page.locator('[data-palette-pick="trans"]').click();
  await page.locator(`[data-segment="${theme}"]`).click();
  await page.waitForFunction(
    (want) =>
      document.documentElement.dataset.palette === 'trans' &&
      document.documentElement.dataset.theme === want,
    theme
  );
};

const strip = async () => {
  await page.mouse.move(4, 4);
  await page.evaluate(() => {
    for (const toast of document.querySelectorAll('[data-toast]')) toast.remove();
    for (const bar of document.querySelectorAll('.demo-bar')) bar.remove();
    document.body.classList.remove('has-demo-bar');
  });
};

/** A band from one selector's top to another's bottom, measured against the
    app frame rather than the viewport - the frame is what a phone shows. */
const crop = async (name, from, to, note) => {
  await strip();
  await page.locator(from).first().scrollIntoViewIfNeeded().catch(() => {});
  await page.waitForTimeout(250);
  const box = await page.evaluate(
    ([a, b]) => {
      const frame = document.querySelector('[data-app-root]').getBoundingClientRect();
      const head = document.querySelector(a)?.getBoundingClientRect();
      const foot = document.querySelector(b ?? a)?.getBoundingClientRect();
      if (!head || !foot) return null;
      const top = Math.max(head.top - 10, frame.top);
      return {
        x: frame.x,
        y: top,
        width: frame.width,
        height: Math.min(foot.bottom - top + 14, frame.bottom - top)
      };
    },
    [from, to]
  );
  if (!box || box.height < 8) {
    errors.push(`${name}: nothing matched ${from} / ${to}`);
    return;
  }
  await page.screenshot({ path: `${outDir}/${tag}-${name}.png`, clip: box });
  shots.push({ name, note });
};

/** Plays whatever media element is inside `within` and lets it run, so the
    playhead is somewhere in the middle of the track. Driven through the
    element rather than the play control, because on the side this is being
    compared against there is no play control to click. */
const playFor = async (within, ms = 2200) => {
  await page.evaluate((sel) => {
    const el = document.querySelector(`${sel} audio, ${sel} video`);
    if (el) {
      el.currentTime = 0;
      void el.play();
    }
  }, within);
  await page.waitForTimeout(ms);
};

const pause = async (within) => {
  await page.evaluate((sel) => {
    const el = document.querySelector(`${sel} audio, ${sel} video`);
    el?.pause();
  }, within);
};

/** Imports a file through the app's own picker, which is a transient input
    the page creates and clicks (data/fileDialog.ts).

    The type is stated rather than inferred: a `.webm` holding audio is
    guessed as `video/webm` from its extension, and the picker refuses
    anything whose type does not begin `audio/` (stores/voiceRecording.ts).
    A recording exported by this app arrives as `audio/webm`, which is what
    is handed over here. */
const importFile = async (trigger, file, mimeType) => {
  const chooser = page.waitForEvent('filechooser');
  await page.locator(trigger).click();
  await (await chooser).setFiles({
    name: file.split('/').pop(),
    mimeType,
    buffer: await readFile(file)
  });
};

const editorAtToday = async () => {
  await settle('/entry/new/today');
  await page.waitForSelector('[data-add-recording-file]');
};

try {
  for (const theme of THEMES) {
    await dress(theme);

    /* 1 and 2. The editor's two unsaved call sites: a recording and a video
       note just added, playing from bytes with nothing stored yet. */
    await editorAtToday();
    await page.locator('[data-mood="3"]').click();
    await importFile('[data-add-recording-file]', media.voice, 'audio/webm');
    await page.waitForSelector('.recording-row');
    await page.waitForTimeout(900);
    await crop(
      `editor-audio-rest-${theme}`,
      '.recording-list',
      '.recording-row:last-of-type',
      `${theme}: a recording just added to an entry, at rest`
    );
    await playFor('.recording-row');
    await crop(
      `editor-audio-playing-${theme}`,
      '.recording-list',
      '.recording-row:last-of-type',
      `${theme}: the same recording mid-play, the playhead about two seconds in`
    );
    await pause('.recording-row');

    await importFile('[data-add-video-file]', media.landscape, 'video/webm');
    await page.waitForSelector('.video-row', { timeout: 30000 });
    await page.waitForTimeout(1200);
    await crop(
      `editor-video-rest-${theme}`,
      '.video-row',
      '.video-row',
      `${theme}: a video note just added, at rest - the first decoded frame is the still, and no poster is stored`
    );
    await playFor('.video-row');
    await crop(
      `editor-video-playing-${theme}`,
      '.video-row',
      '.video-row',
      `${theme}: the same note mid-play, wearing the recording's transport under its frame`
    );
    await pause('.video-row');

    /* Saved, which is what turns both of those into the stored call sites. */
    await page.locator('[data-save]').click();
    await page.waitForTimeout(1500);

    /* 3. The memo browser, which is every recording in the journal. */
    await settle('/media/voice/memos');
    await page.waitForSelector('[data-memo-row]');
    await page.waitForTimeout(1200);
    await crop(
      `memos-rest-${theme}`,
      '.screen [data-memo-reading], .screen .kit-card, .screen',
      '[data-memo-row]:first-of-type',
      `${theme}: the memo browser's opening reading and its first row, at rest`
    );
    await playFor('[data-memo-row]:first-of-type');
    await crop(
      `memos-playing-${theme}`,
      '[data-memo-row]:first-of-type',
      '[data-memo-row]:first-of-type',
      `${theme}: a memo playing from the browser`
    );
    await pause('[data-memo-row]:first-of-type');

    /* 4. The stored call sites: the entry this recording belongs to, reached
       the way the memo browser reaches it. Deterministic, unlike picking an
       entry off the day screen - the demo persona has entries of its own
       today and the newest card is not necessarily the one just saved. */
    await settle('/media/voice/memos');
    const entry = page.locator('[data-open-entry]').first();
    if (await entry.count()) {
      await entry.click();
      await page.waitForSelector('[data-add-recording-file]', { timeout: 20000 });
      await page.waitForTimeout(1500);
      await crop(
        `editor-stored-audio-${theme}`,
        '.recording-list',
        '.recording-row:last-of-type',
        `${theme}: the same recording after the entry was saved, read back from its stored file`
      );
      await crop(
        `editor-stored-video-${theme}`,
        '.video-row',
        '.video-row',
        `${theme}: the stored video note, read back from its file`
      );
    } else {
      errors.push(`editor-stored-${theme}: no entry card on /day/today`);
    }

    /* 5. A portrait note, which has to fit its row as well as a landscape
       one does. Shot once, in the theme that shows the frame's edges. */
    if (theme === 'light') {
      await editorAtToday();
      await importFile('[data-add-video-file]', media.portrait, 'video/webm');
      await page.waitForSelector('.video-row', { timeout: 30000 });
      await page.waitForTimeout(1200);
      await crop(
        'video-portrait',
        '.video-row',
        '.video-row',
        'A portrait note in the same row as a landscape one: the frame is the row, the picture is contained in it'
      );
    }
  }

  /* 6. The voice compare screen, the fifth call site. Nothing in the demo
     journal is a benchmark, so two are recorded through the real flow with
     the fake microphone - the same recipe voice-compare-gallery.mjs uses. */
  await dress('light');
  const recordOneBenchmark = async () => {
    await page.goto(`${base}/practice/voice?tab=record`, { waitUntil: 'networkidle' });
    await page.waitForSelector('[data-vb-record]');
    await page.locator('[data-vb-record]').click();
    /* Long enough to clear the reading floor the passage step measures
       against, which is its word count times a per-word constant
       (audio/quality.ts) - the two and a half seconds this recipe used
       before ticket 41 added that floor now fails the gate and lands in
       retry. */
    await page.waitForTimeout(22000);
    await page.locator('[data-vb-stop]').click();
    await page.waitForSelector('[data-vb-skip]', { timeout: 30000 });
    await page.locator('[data-vb-record]').click();
    await page.waitForSelector('[data-vb-skip]', { timeout: 25000 });
    await page.locator('[data-vb-skip]').click();
    await page.waitForSelector('[data-vb-skip]', { timeout: 25000 });
    await page.locator('[data-vb-skip]').click();
    await page.waitForSelector('[data-vb-save]', { timeout: 25000 });
    await page.waitForTimeout(300);
    await page.locator('[data-vb-save]').click();
    /* The flow's destination belongs to whoever mounted it, so what is
       waited on is the flow being over rather than a path. */
    await page.waitForSelector('[data-vb-save]', { state: 'detached', timeout: 20000 });
    await page.waitForTimeout(600);
  };
  await recordOneBenchmark();
  await recordOneBenchmark();

  /* The compare half of the voice screen, asked for by its own tab
     parameter rather than by clicking a segment whose label has moved
     twice since the recipe this borrowed was written. */
  await settle('/practice/voice?tab=compare');
  await page.waitForSelector('[data-voice-cell]', { timeout: 20000 });
  const cells = page.locator('[data-voice-cell]');
  await cells.nth(0).locator('.kit-row-main').click();
  await cells.nth(1).locator('.kit-row-main').click();
  await page.locator('[data-compare]').click();
  await page.waitForSelector('.vc-take');
  await page.waitForTimeout(1200);
  await crop(
    'compare-rest',
    '.vc-stack',
    '.vc-take:first-of-type',
    'The voice compare screen: a take on each side, each with the same transport'
  );
  await playFor('.vc-take');
  await crop(
    'compare-playing',
    '.vc-stack',
    '.vc-take:first-of-type',
    'A take playing on the compare screen'
  );
  await pause('.vc-take');

  /* 7. The photo journey's timelapse preview - the surface the ticket did
     not count, which was a seventh `<video controls>` and is the same
     player now. Guarded: a timelapse records as it plays, so this is the
     one scene that can legitimately take too long, and a sign-off without
     it is worth more than a run that dies here. */
  try {
    await settle('/media/photos/export');
    if (await page.locator('[data-segment="timelapse"]').count()) {
      await page.locator('[data-segment="timelapse"]').click();
      await page.waitForTimeout(300);
      await page.locator('[data-generate]').click();
      await page.waitForSelector('.journey-preview [data-transport]', { timeout: 120000 });
      await page.waitForTimeout(1200);
      await crop(
        'timelapse-preview',
        '.journey-preview',
        '.journey-preview [data-transport]',
        'The photo journey preview: a timelapse this app just rendered, played through the same transport as a recording and a note'
      );
    } else {
      errors.push('timelapse-preview: this browser cannot record, so the screen offers no timelapse');
    }
  } catch (error) {
    errors.push(`timelapse-preview: ${error.message.split('\n')[0]}`);
  }
} finally {
  await writeFile(
    `${outDir}/${tag}-shots.json`,
    JSON.stringify({ tag, shots, errors }, null, 2) + '\n'
  );
  await page.close();
  await browser.close();
  await app.close();
}

console.log(`${shots.length} shots into ${outDir} as ${tag}-*`);
for (const shot of shots) console.log(`  ${shot.name}: ${shot.note}`);
if (errors.length) {
  console.log('\nproblems:');
  for (const error of errors) console.log(`  ${error}`);
  process.exitCode = 1;
}
