/* Stamp palette, mood, theme, accessibility attributes, icon and
   manifest (ADR-0009). The layout applies these once running.
   src/app.html duplicates the rule before first paint to avoid a theme
   flash or exposing the flag while disguised. Update both adapters
   and fixtures/document-chrome.json together. The layout supplies
   reactivity, so this function stays rune-free for Node tests. */

import { DISGUISED_PALETTE } from './catalogue.ts';
import type { BootPreferences } from './preferences.ts';

/** The boot preferences the document actually wears - the subset both
    adapters read, so the fixture holds these seven and nothing else. */
export type ChromePreferences = Pick<
  BootPreferences,
  | 'palette'
  | 'moodPreset'
  | 'theme'
  | 'a11yTextSizeBoost'
  | 'a11yLegibilityBoost'
  | 'a11yMotionReduce'
  | 'disguise'
>;

/** What the two media queries report. Passed in rather than read here,
    because the pre-paint script asks them directly and the layout keeps
    them in state through a change listener. */
export interface SystemPreferences {
  prefersDark: boolean;
  prefersReducedMotion: boolean;
}

/** The disguised tab icon. */
const NEUTRAL_TAB_ICON = 'favicon-notes.svg';

export interface DocumentChrome {
  palette: string;
  moodPreset: string;
  theme: 'light' | 'dark';
  a11yTextSize: 'normal' | 'boost';
  a11yLegibility: 'normal' | 'boost';
  a11yMotion: 'normal' | 'reduce';
  icon: string;
  manifest: string;
}

/** `journalShown`: the journal is on screen, not a gate, a splash or a
    boot still under way. The pre-paint script only ever runs before that,
    so it is the layout alone that passes true. */
export function documentChrome(
  prefs: ChromePreferences,
  system: SystemPreferences,
  journalShown = false
): DocumentChrome {
  return {
    /* Disguised, nothing before the journal shows wears the person's flag
       (security-scan ticket 08, GD-043): a gate is the screen most likely
       to be seen by someone else, and the flag names who holds the phone. */
    palette: prefs.disguise && !journalShown ? DISGUISED_PALETTE : prefs.palette,
    moodPreset: prefs.moodPreset,
    /* `system` is a stored value and not an attribute: the document only
       ever carries a resolved light or dark. */
    theme: prefs.theme === 'system' ? (system.prefersDark ? 'dark' : 'light') : prefs.theme,
    a11yTextSize: prefs.a11yTextSizeBoost ? 'boost' : 'normal',
    a11yLegibility: prefs.a11yLegibilityBoost ? 'boost' : 'normal',
    /* Either source reducing motion reduces it; the preference can only
       turn it off, never back on against the system's answer. */
    a11yMotion: prefs.a11yMotionReduce || system.prefersReducedMotion ? 'reduce' : 'normal',
    /* The tab icon follows the flag, because a link element can be
       swapped while the tab is open - unlike the manifest's install icon,
       which is read once at install time and so stays the default's.
       One file per palette, generated by
       scripts/render-mark.mjs; tests/node/ui/mark-assets.test.ts is what stops a
       ninth palette naming a file nobody rendered. */
    icon: prefs.disguise ? NEUTRAL_TAB_ICON : `favicon-${prefs.palette}.svg`,
    manifest: prefs.disguise ? 'manifest-notes.webmanifest' : 'manifest.webmanifest'
  };
}
